import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createLocalBackend} from '../backend.mjs';
import {AdminService} from '../service.mjs';
import {createPanelServer} from '../server.mjs';
const local=await createLocalBackend(),service=new AdminService(local.backend),server=createPanelServer(service);
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch(process.env.SHAMROCK_CHROMIUM_PATH?{executablePath:process.env.SHAMROCK_CHROMIUM_PATH}:{});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},timezoneId:'America/Indiana/Indianapolis'}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/session',r=>r.fulfill({status:401,json:{error:{code:'SIGN_IN_REQUIRED',message:'Sign in to SHAMROCK.'}}}));
 await page.clock.install({time:new Date('2026-11-17T18:00:00Z')});
 await page.goto(`http://127.0.0.1:${server.address().port}/?signin=SERVICE_LIMIT_REACHED`);
 await page.getByText('Sign in with the school email listed in SHAMROCK.',{exact:true}).waitFor({timeout:10000});
 assert.match(await page.locator('.login').innerText(),/free service limit.*7:00 PM EST/);
 assert.equal(await page.getByText('Use the Google account your administrator has authorized.',{exact:true}).count(),0);
 await page.clock.fastForward(200);
 await page.screenshot({path:'/tmp/shamrock-signin-limit-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'/tmp/shamrock-signin-limit-mobile.png'});
 await page.unroute('**/api/session');
 let reads=0;
 await page.route('**/api/state',async r=>{reads++;if(reads===1){await r.continue();return;}await r.fulfill({status:503,headers:{'Retry-After':'3600'},json:{error:{code:'SERVICE_LIMIT_REACHED',message:'Daily allowance exhausted.'}}});});
 await page.goto(`http://127.0.0.1:${server.address().port}/`);
 await page.getByRole('button',{name:'Add event',exact:true}).waitFor({timeout:10000});
 await page.clock.fastForward(61000);
 await page.getByText('Daily service limit reached. Automatic updates will resume after the allowance resets.',{exact:true}).waitFor({timeout:10000});
 assert.equal(reads,2);
 await page.clock.fastForward(300000);
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
 await page.waitForTimeout(50);
 assert.equal(reads,2,'quota stops timers and focus-triggered refreshes');
 await page.clock.fastForward(3360000);
 await page.waitForTimeout(50);
 assert.equal(reads,3,'automatic refresh resumes when Retry-After expires');
 assert.deepEqual(errors,[]);
 console.log('PASS: localized quota message, school-email guidance, desktop/mobile layout, no framework/runtime errors, background and focus reads stop during quota cooldown.');
}finally{await browser.close();await new Promise(r=>server.close(r));service.close();await local.dispose();}
